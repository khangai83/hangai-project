--    «Авто машины хэтчбек ийг хасна уу, седан ийг суудлын машин болго»
--
-- 📐 ХИЙЦ (ЗӨВХӨН `section = 'auto'` мөрүүдэд хүрнэ):
--    • «Хэтчбек»  → «Суудлын машин»   (хэтчбек нь суудлын машины нэг хэлбэр)
--    • «Седан»    → «Суудлын машин»
--    ⚠️ ЗАР УСТГАХГҮЙ — зөвхөн `property_type` нэрийг сольж, ХАДГАЛНА.
--       Ингэснээр хуучин зарууд «Суудлын машин» шүүлтэд харагдана
--       (нэр солихгүй бол тэдгээр зар зөвхөн «Бүх зар»-д үлдэж, дэд
--       төрлийн тооноос ГАДУУР орхигдоно ✗).
--
-- ⚠️ УРЬДЧИЛСАН НӨХЦӨЛ: `0016_listing_sections.sql` ЗААВАЛ ажилласан байх
--    (`listings.section` багана).
--    `lib/locationData.js` → `SECTIONS.auto.subtypes` нь ОДОО 9 дэд төрөлтэй
--    («Суудлын машин» орсон, «Седан»/«Хэтчбек» хасагдсан).
--
-- ⚠️ АЖИЛЛУУЛАХ: Supabase Dashboard → SQL Editor → бүтнээр нь RUN.
