-- ---------- 1. Хуучин дэд төрлүүдийг шинэ модны нэр рүү шилжүүлэх ----------
update public.listings as l
   set property_type = m.new_type
  from (values
    ('Тавилга, буйдан',          'Буйдан, кресло'),
    ('Гал тогооны хэрэгсэл',     'Гал тогооны хэрэгсэл, сав суулга'),
    ('Гэр ахуйн техник',         'Зуух, пийшин'),
    ('Гэрэлтүүлэг',              'Абажур, гэрэл, чийдэн'),
    ('Хивс, дэвсгэр',            'Хивс, дорож, дэвсгэр'),
    ('Ор, унтлагын хэрэгсэл',    'Ор, матрас'),
    ('Цэвэрлэгээ, угаалга',      'Угаалгын өрөө, цэвэрлэгээний хэрэгсэл'),
    ('Чимэглэл, зураг',          'Гэрийн чимэглэл, тохижилт'),
    ('Хадгалах шүүгээ, тавиур',  'Шкаф, комод, авдар')
  ) as m(old_type, new_type)
 where l.section = 'home'
   and l.property_type = m.old_type;

-- ---------- 2. Модноос ГАДУУР үлдсэн утгыг «Бусад» болгох (сүлжээ) ----------
-- ⚠️ ЯАГААД: дээрх 9 солилт нь МЭДЭГДЭЖ буй хуучин нэрс. Хэрэв DB-д өөр
--    (гараар бичсэн, хуучин хувилбарын) утга байвал тэр зар нь дэд төрлийн
--    жагсаалтаас гадуур үлдэж, шүүлт/тооллоос ХАСАГДАХ байсан ✗
--    → «Бусад» нь шинэ модонд байгаа тул аюулгүй газар ✓ (0021-ийн зарчим)
-- ℹ️ Хэрэв бүх мөр дээрх солилтоор хамрагдсан бол энэ UPDATE нь **0 мөр** ✓
update public.listings
   set property_type = 'Бусад'
 where section = 'home'
   and property_type is not null
   and property_type not in (
     -- 🛋️ Тавилга (13)
     'Зочны өрөөний', 'Унтлагын өрөөний', 'Гал тогооны', 'Үүдний өрөөний',
     'Оффисын тавилга', 'Буйдан, кресло', 'Ор, матрас', 'Шкаф, комод, авдар',
     'Ширээ, сандал', 'Тавиур, полк', 'Толь', 'Сейф', 'Бусад',
     -- 🧺 Гэр ахуйн бараа (9)
     'Абажур, гэрэл, чийдэн', 'Угаалгын өрөө, цэвэрлэгээний хэрэгсэл',
     'Гал тогооны хэрэгсэл, сав суулга', 'Гэрийн чимэглэл, тохижилт',
     'Хивс, дорож, дэвсгэр', 'Цагаан хэрэглэл, хөнжил, дэр',
     'Хөшиг, тюль, бүтээлэг', 'Зуух, пийшин', 'Өлгүүр'
   );

