update public.listings
   set property_type = 'Бусад'
 where section = 'hobby'
   and property_type is not null
   and property_type not in (
     -- ⚠️ `lib/locationData.js` → `HOBBY_SUBTYPES`-ийн 19 утгатай ЯГ ИЖИЛ
     --    (нэг нь ч мартагдвал тэр зар баригдахгүй өнгөрнө ✗ — тест түгждэг ✓)
