-- ---------- 1. ХАСАГДСАН 2 нэрийг «Бусад» болгох ----------
update public.listings
   set property_type = 'Бусад'
 where section = 'hobby'
   and property_type in (
     'Кемпинг', 'Усанд сэлэх'
   );

