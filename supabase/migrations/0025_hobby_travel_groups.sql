-- ---------- 1. Хуучин «Аяллын хэрэгсэл» → шинэ бүлгийн «Бусад» ----------
-- ℹ️ Мэдээлэл бүрэн бол `attrs->>'model'`-оор нарийн хувааж болно (хэрэгцээгүй):
--    update public.listings set property_type = case attrs->>'model'
--      when 'Аяллын гэрэл' then 'Аяны гэрэл, power bank'
--      … end where section = 'hobby' and property_type = 'Аяллын хэрэгсэл';
update public.listings
   set property_type = 'Бусад'
 where section = 'hobby'
   and property_type = 'Аяллын хэрэгсэл';

-- ---------- 2. Модноос ГАДУУР үлдсэн утгыг «Бусад» болгох (сүлжээ) ----------
-- ⚠️ ЯАГААД: дээрх солилт нь МЭДЭГДЭЖ буй 1 хуучин нэр. Хэрэв DB-д өөр
--    (гараар бичсэн, хуучин хувилбарын) утга байвал тэр зар нь дэд төрлийн
--    жагсаалтаас гадуур үлдэж, шүүлт/тооллоос ХАСАГДАХ байсан ✗
--    → «Бусад» нь шинэ модонд байгаа тул аюулгүй газар ✓ (0022-ын зарчим)
-- ℹ️ Хэрэв бүх мөр дээрх солилтоор хамрагдсан бол энэ UPDATE нь **0 мөр** ✓
update public.listings
   set property_type = 'Бусад'
 where section = 'hobby'
   and property_type is not null
   and property_type not in (
     -- 🏕 Аяллын хэрэгсэл (12) — 3 дахь түвшин
     'Аяны гэрэл, power bank', 'Аяны хоолны хэрэгсэл', 'Аяны ор гудас',
     'Аяны ширээ сандал', 'Аяны цүнх, чемодан', 'Аяны цахилгаан хэрэгсэл',
     'Бассейн, зөөврийн душ', 'Завь ба дагалдах хэрэгсэл', 'Майхан, сүүдрэвч',
     'Нүдний дуран, телескоп', 'Уулын хэрэгсэл', 'Бусад',
     -- 🎣 Доод түвшингүй 6 (2 дахь түвшин)
     'Загас ан агнуур', 'Ном, сонин, сэтгүүл', 'Спортын хэрэгсэл',
     'Хөгжмийн зэмсэг', 'Цуглуулга', 'Унадаг дугуй, сэлбэг'
   );

