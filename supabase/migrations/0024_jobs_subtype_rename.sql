-- ---------- 1. Хуучин дэд төрлүүдийг шинэ нэр рүү шилжүүлэх ----------
update public.listings as l
   set property_type = m.new_type
  from (values
    ('IT, программист',        'МТ, харилцаа холбоо'),
    ('Борлуулалт, маркетинг',  'Борлуулалт, худалдаа'),
    ('Нягтлан бодох, санхүү',  'Банк, санхүү, нябо, нярав'),
    ('Инженер, техник',        'Үйлдвэрлэл'),
    ('Барилга, засвар',        'Барилга, дэд бүтэц'),
    ('Үйлчилгээ, үйлдвэрлэл',  'Үйлчилгээ'),
    ('Хүний нөөц, захиргаа',   'Захиргаа, Хүний нөөц'),
    ('Жолооч',                 'Тээвэр, гааль, агуулах'),
    ('Хамгаалалт',             'Харуул хамгаалалт'),
    ('Худалдаа, касс',         'Борлуулалт, худалдаа'),
    ('Боловсрол, сургалт',     'Боловсрол, шинжлэх ухаан'),
    ('Эрүүл мэнд',             'Эрүүл мэнд, эм зүй'),
    ('Ресторан, зочид буудал', 'Ресторан, кафе, паб'),
    ('Хөдөө аж ахуй',          'ХАА, Байгаль экологи'),
    ('Бусад',                  'Туслах ажилчин')
  ) as m(old_type, new_type)
 where l.section = 'jobs'
   and l.property_type = m.old_type;

-- ---------- 2. Жагсаалтаас ГАДУУР үлдсэн утгыг «Туслах ажилчин» болгох ----------
-- ⚠️ ЯАГААД: §1 нь МЭДЭГДЭЖ буй хуучин 15 нэр. Хэрэв DB-д өөр (гараар бичсэн,
--    хуучин хувилбарын) утга байвал тэр зар нь дэд төрлийн жагсаалтаас гадуур
--    үлдэж, шүүлт/тооллоос ХАСАГДАХ байсан ✗ → шинэ жагсаалтын ЕРӨНХИЙ
--    буух газар «Туслах ажилчин» ✓ (0021/0022-ын зарчим: «Бусад»)
-- ℹ️ Хэрэв бүх мөр §1-ээр хамрагдсан бол энэ UPDATE **0 мөр** ✓
update public.listings
   set property_type = 'Туслах ажилчин'
 where section = 'jobs'
   and property_type is not null
   and property_type not in (
     'Авто үйлчилгээ, засвар', 'Аялал жуулчлал, зочид буудал',
     'Банк, санхүү, нябо, нярав', 'Барилга, дэд бүтэц',
     'Боловсрол, шинжлэх ухаан', 'Борлуулалт, худалдаа',
     'Гоо сайхан, фитнес, спорт', 'Гүйцэтгэх удирдлага',
     'Дизайн, урлаг, уран сайхан', 'Захиргаа, Хүний нөөц',
     'Маркетинг, PR менежмент', 'МТ, харилцаа холбоо',
     'Менежер, төлөөлөгч', 'Ресторан, кафе, паб',
     'Сэтгүүлч, редактор', 'Тээвэр, гааль, агуулах',
     'Туслах ажилчин', 'Уул уурхай', 'Харуул хамгаалалт',
     'ХАА, Байгаль экологи', 'Хууль, эрх зүй', 'Эрүүл мэнд, эм зүй',
     'Үйлдвэрлэл', 'Үйлчилгээ', 'Цагийн ажил',
     'Хөгжлийн бэрхшээлтэй иргэн ажиллах боломжтой'
   );

