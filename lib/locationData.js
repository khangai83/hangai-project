/**
 * 📅 ОНЫ ХҮРЭЭНИЙ түлхүүрийг задална: `'year_from'` → `{ base:'year', dir:'from' }`.
 *
 * ⚠️ Утга нь `attrs` (jsonb) дотор `<талбар>_from` / `<талбар>_to` гэж
 *    хадгалагддаг (URL: `?attr_year_from=2015`) — учир нь `attrs` нь тэгш
 *    хавтгай объект (шүүлтийн нэг түлхүүр = нэг утга) ✓
 * ⚠️ Хүрээ БИШ түлхүүрт `null` буцаана — `lib/queries.js` ба `HomeClient`
 *    ХОЁУЛАА үүнийг ашиглана (давхардсан regex нь зөрүү үүсгэдэг ✗)
 */
export function parseAttrRangeKey(key) {
  const m = /^(.+)_(from|to)$/.exec(String(key || ''));
  return m ? { base: m[1], dir: m[2] } : null;
}

/** Хүрээний ХОЁР түлхүүрийн нэр (`base:'year'` → `from:'year_from', to:'year_to'`) */
export function getAttrRangeKeys(base) {
  return { from: `${base}_from`, to: `${base}_to` };
}

/**
 * Хэсгийн attr талбарын тодорхойлолт олох
 */
export function getAttrField(section, key) {
  const sec = getSection(section);
  return (sec.attrFields || []).find((f) => f.key === key) || null;
}

/**
 * 💻 ФОРМД ХАРАГДАХ attr талбарууд — хэсэг + ДЭД ТӨРӨЛӨӨР шүүнэ
 * (2026-09-30 (6), хэрэглэгчийн хүсэлт: «Notebook сонгосон үед л … харагдах»).
 *
 * ⚠️ ЯАГААД ХЭРЭГТЭЙ ВЭ: хэсгийн `attrFields` нь БҮХ дэд төрөлд НИЙТЛЭГ
 *    байдаг тул «Дэлгэц/CPU/RAM/Хард» нь Mouse, Keyboard, тонер, тоглоом
 *    дээр ч харагдаж байв ✗ → `onlySubtypes` жагсаалттай талбар нь ЗӨВХӨН
 *    тэр дэд төрлүүдэд гарна ✓ (`lib/locationData.js` → `PC_SPEC_SUBTYPES`)
 *
 * ⚠️ `onlySubtypes` БАЙХГҮЙ талбар нь ХУУЧИН зан төлөвөөр (бүх дэд төрөлд)
 *    харагдана ✓ — бусад 11 хэсэгт ямар ч өөрчлөлт БАЙХГҮЙ ✓
 * 🆕 2026-10-05 (56): 💻 🏷️ «Брэнд» ба 🖥️ «Загвар» ч `onlySubtypes`-тай болов
 *    (хэрэглэгчийн хүсэлт: «notebook ээс бусад хэсэгт Брэнд Загвар гэсэн утга
 *    оруулахгүй») ⇒ 💻-д `onlySubtypes`-тай талбар ЯГ 6 (brand · model ·
 *    screen · cpu · ram · storage) — бүгд Notebook-ийн гэр бүлд л ✓
 * ⚠️ `getAttrField` (картын мөр/шүүлт) нь ЭНЭ шүүлтийг ХИЙХГҮЙ: хуучин
 *    заруудын `attrs` нь DB-д хэвээр байх ба `formatAttrsLine` ба sidebar-ийн
 *    шүүлт ХӨНДӨГДӨХГҮЙ ✓ (шугам үүсгэхгүй ✓)
 *
 * @param {string} section   хэсэг (`computers` …)
 * @param {string} [subtype] сонгосон дэд төрөл; ⚠️ ХООСОН бол `onlySubtypes`
 *    талбарууд ХАРАГДАХГҮЙ (эхлээд дэд төрлөө сонгоно ✓)
 */
export function getAttrFields(section, subtype = '') {
  const sec = getSection(section);
  return (sec.attrFields || []).filter(
    (f) => !Array.isArray(f.onlySubtypes) || (subtype && f.onlySubtypes.includes(subtype)),
  );
}

/**
 * Sidebar-д харагдах attr шүүлтүүд.
 *
 * ⚠️ ГУРВАН ТӨРӨЛ байна:
 *   ① `select` + `options`  → энгийн `<select>` (цөөн сонголттой: 🔧 Хөдөлгүүр;
 *      ⚠️ 2026-10-03 (19)/(21)/(22)-оос 🎨 Өнгө · ✅ Төлөв · ⚙️ хайрцаг ·
 *      ⛽ Түлш нь `chips`+`multi` тугтай тул SIDEBAR-д чип болно — тэдгээрийн
 *      `type` нь `'select'` ХЭВЭЭР (форм нэг утга хадгална ✓);
 *      🆕 2026-10-05 (42): 💼 🕒 Ажлын цаг · 📊 Туршлага · 📈 Мэргэжлийн
 *      түвшин ч мөн адил ОЛОН СОНГОЛТТОЙ ЧИП болов (`chips`+`multi` ✓))
 *   ② `select` + `searchable` → **хайлттай combobox** (`SearchableSelect`) —
 *      урт жагсаалтаас бичиж хайх + гараар бичих (ж: 🏷️ Брэнд — 95 утга)
 *   ③ `filterable` (текст эсвэл `range`) → гараар бичих шүүлт —
 *      📅 оны хүрээ (Доод/Дээд) ба 🚙 Загвар (`TextFilter`)
 * ⚠️ `type` нь `'select'` ХЭВЭЭР байгаа combobox нь энд хэвээр багтана ✓
 * ⚠️ 2026-10-01: 🚙 «Загвар» нь `optionsFrom: 'brand'` мета-тай болов (БРЭНДЭЭС
 *    ХАМААРАХ сонголт) — энэ функц ХӨНДӨГДӨХГҮЙ (төрөл нь `text` + `filterable`
 *    хэвээр тул ③-т багтсаар байна ✓); зөвхөн UI нь брэнд сонгогдсон үед
 *    `SearchableSelect` болгож дүрсэлнэ (`components/HomeClient.jsx`)
 *
 * 🖥 2026-10-03 (7): 2 дахь параметр `subtype` нэмэгдэв — `onlySubtypes`-тай
 *    талбар нь ЗӨВХӨН тэр дэд төрлүүдэд харагдана (формойн `getAttrFields`-тэй
 *    ЯГ ИЖИЛ дүрэм ✓). ⚠️ ЯАГААД: 💻 Notebook-ийн 📺 Дэлгэц · ⚙️ CPU · 🧠 RAM ·
 *    💾 Хард шүүлтүүд нь дэд төрөл сонгоогүй эсвэл Mouse/Keyboard/тонер гэх мэт
 *    ХОЛДУУ дэд төрөлд ч харагдаж, «утгагүй шүүлт» болох байв ✗
 *    ⚠️ `subtype` ХООСОН бол `onlySubtypes` талбарууд ХАРАГДАХГҮЙ (эхлээд
 *       дэд төрлөө сонгоно ✓ — формтой ижил)
 *    ⚠️ `subtype` дамжуулахгүй хуучин дуудлага (`getAttrFilters('auto')`) нь
 *       ХУУЧИН зан төлөвөөр ажиллана ✓ (зөвхөн 💻 хэсэгт `onlySubtypes` байна)
 *
 * 🏷️ 2026-10-03 (20): `filterSubtypes` нэмэгдэв — ЗӨВХӨН SIDEBAR-д хүчинтэй
 *    хязгаарлалт (`onlySubtypes`-аас ЯЛГААТАЙ нь: ФОРМЫГ хөндөхгүй ✓).
 *    ⚠️ ЯАГААД: хэрэглэгчийн хүсэлт «Notebook ээс бусад хайлтын хэсэгт Брэнд
 *    гэж баймааргүй байна даа» ⇒ 💻 🏷️ «Брэнд» нь Mouse/Keyboard/Дэлгэц/
 *    принтер/тонер/тоглоом/iPad/чихэвч … болон дэд төрөл СОНГООГҮЙ үед
 *    шүүлтээс ГАРНА, харин форм дээр (ж: iPad-ийн брэнд) ХЭВЭЭР асууна ✓
 *    (`getAttrField` — картын мөр/дэлгэрэнгүй — ч ХӨНДӨГДӨХГҮЙ ✓)
 * 🆕 2026-10-05 (56): 💻 «Брэнд»/«Загвар» нь `onlySubtypes`-тай БОЛСОН тул
 *    дээрх хязгаарлалт нь ФОРМ БА ШҮҮЛТ ХОЁУЛАНД ижил дүрмээр ажиллана ✓
 *    (шүүлтийн жагсаалт ХӨНДӨГДӨӨГҮЙ — `onlySubtypes`-ийн салбар эхэлж шалгана ✓)
 *
 * @param {string} section хэсэг (`computers` …)
 * @param {string} [subtype] сонгосон дэд төрөл (`?type=Apple`; ⚠️ ХООСОН бол
 *   `onlySubtypes`/`filterSubtypes` талбарууд ХАРАГДАХГҮЙ)
 */
export function getAttrFilters(section, subtype = '') {
  const sec = getSection(section);
  return (sec.attrFilters || [])
    .map((k) => getAttrField(section, k))
    .filter((f) => {
      if (!f) return false;
      // 🖥 Зөвхөн тухайн дэд төрөлд харагдах талбар (`onlySubtypes`)
      if (Array.isArray(f.onlySubtypes) && !(subtype && f.onlySubtypes.includes(subtype))) {
        return false;
      }
      // 🏷️ 2026-10-03 (20): ЗӨВХӨН SIDEBAR-д хүчинтэй хязгаарлалт
      //    (`filterSubtypes` — ж: 💻 «Брэнд» нь Notebook-ийн гэр бүлд л).
      //    ⚠️ ФОРМ ХӨНДӨГДӨХГҮЙ (`getAttrFields` энийг хардаггүй ✓)
      if (Array.isArray(f.filterSubtypes) && !(subtype && f.filterSubtypes.includes(subtype))) {
        return false;
      }
      if (f.type === 'select') return Array.isArray(f.options) && f.options.length > 0;
      // ✍️ гараар бичих текст шүүлт (ж: Загвар) эсвэл 📅 оны хүрээ
      return f.filterable === true;
    });
}

