/**
 * 🗺 ОЛОН дүүрэг/сумын хороодын НЭГДЭЛ (2026-10-03, хэрэглэгчийн хүсэлт:
 * «Дүүрэг / Сум-ийг Өрөөний тоо хайхтай адилхан олон сонголт хийх боломжтой
 * болго») — sidebar-д 2+ дүүрэг сонгосон үед хорооны жагсаалт нь
 * сонгосон БҮХ дүүргийн хороог (дүүргийн дарааллаар) харуулна ✓
 *
 *   getKhoroosForDistricts('Улаанбаатар', ['Баянгол', 'Сүхбаатар'])
 *     → ['1-р хороо' … '33-р хороо']   (Баянгол 33 + Сүхбаатар 20-иос
 *        «1-р хороо»…«20-р хороо» нь ДАВХЦАЖ байгаа тул ХАСАГДАНА) ✓
 *   getKhoroosForDistricts('Улаанбаатар', []) → []   (хорооны блок нуугдана)
 *
 * ⚠️ Хорооны НЭР нь («3-р хороо») дүүрэг хооронд ДАВХЦДАГ тул:
 *    ① Жагсаалтаас давхцлыг ХАСНА — эс бөгөөс чип «1-р хороо» хоёр удаа
 *       харагдаж, нэгийг дарвал хоёулаа асна (хэрэглэгчид алдаа мэт) ✗
 *    ② DB дээрх `khoroo IN (…)` нь `district IN (…)`-тай ХАМТ явдаг тул
 *       «3-р хороо» гэдэг нь сонгосон дүүргүүдийн аль нэгний 3-р хороог
 *       илэрхийлнэ — энэ нь өмнөх (2026-09-25-ний) олон дүүрэгтэй
 *       хувилбарын ЯГ ИЖИЛ зан төлөв ✓
 * ⚠️ `districts` нь МАССИВ эсвэл скаляр (хуучин) байж болно —
 *    `parseDistrictList()` хоёуланг дэмжинэ ✓
 */
export function getKhoroosForDistricts(city, districts) {
  const out = [];
  parseDistrictList(districts).forEach((d) => {
    getKhoroos(city, d).forEach((k) => {
      if (!out.includes(k)) out.push(k);
    });
  });
  return out;
}

