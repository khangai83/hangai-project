export function formatAttrsLine(section, attrs, category = 'sell') {
  if (!attrs || typeof attrs !== 'object') return '';
  const order = CARD_ATTR_ORDER[section];
  if (!order) return '';

  // Он+загвар/брэндийг нэг хэсэг болгож товчлох (зарын сайтуудын хэв маяг).
  // ⚠️ Брэнд/загвар байхгүй бол (Ажил, Үйлчилгээ) КОМПАНИЙН нэрийг толгой болгоно.
  const brand = String(attrs.brand || '').trim();
  const model = String(attrs.model || '').trim();
  const year = String(attrs.year || '').trim();
  const company = String(attrs.company || '').trim();

  const head = [brand, model].filter(Boolean).join(' ') || company;
  const parts = [];
  if (head) parts.push(year ? `${head}, ${year}` : head);
  else if (year) parts.push(year);

  const skip = new Set(['brand', 'model', 'year', 'company']);
  order.forEach((k) => {
    if (skip.has(k)) return;
    const v = attrs[k];
    if (v === undefined || v === null || String(v).trim() === '') return;
    const field = getAttrField(section, k);
    // ⚠️ Нэгжийг нь текстэд оруулсан эсвэл мөрөнд товчлон харуулна
    if (k === 'mileage') parts.push(`${Number(String(v).replace(/\D/g, '')).toLocaleString('en-US')} км`);
    // 🔧 2026-10-01: «Хөдөлгүүр» нь ХҮРЭЭТЭЙ СОНГОЛТ болов — утга нь ӨӨРӨӨ
    //    нэгжтэй («1.5л хүртэл», «Цахилгаан (EV)») тул «л» ЗАЛГАХГҮЙ;
    //    ⚠️ зөвхөн ХУУЧИН/demo тоон утгад («2.5») л залгана ✓
    else if (k === 'engine') {
      parts.push(/^\d+(?:[.,]\d+)?$/.test(String(v).trim()) ? `${v} л` : String(v));
    }
    // ⚠️ «Орж ирсэн он» нь зүгээр «2021» гэвэл «Үйлдвэрлэсэн он»-той
    //    андуурагддаг тул ТАЙЛБАРТАЙ хэлбэрээр («📥 2021 онд орж ирсэн») ✓
    else if (k === 'importYear') parts.push(`📥 ${v} онд орж ирсэн`);
    else if (k === 'salary') parts.push(`₮${Number(String(v).replace(/\D/g, '')).toLocaleString('en-US')}`);
    // ⚠️ «Албан тушаал» нь компанийн дараа icon-ГҮЙ, энгийн текстээр
    else if (k === 'position') parts.push(String(v));
    else if (k === 'ram' || k === 'storage' || k === 'size' || k === 'screen') parts.push(String(v));
    else parts.push(field && field.icon ? `${field.icon} ${v}` : String(v));
  });

  // Ажилд «Ажилд авна» гэдгийг тодруулах (компани бичээгүй бол)
  if (section === 'jobs' && !company) parts.unshift('Ажилд авна');

  return parts.join(' · ');
}

/**
 * 📋 `attrs`-ийг «Зарын дэлгэрэнгүй» ХҮСНЭГТЭД бэлэн мөрүүд болгоно.
 *
 * 🎯 ХЭРЭГЛЭГЧИЙН ХҮСЭЛТ (2026-10-01 (16)): «Автомашин руу орход дэлгэрэнгүй
 *    мэдээлэл харуулаачээ, 2 багана болгоод оруулаарай».
 *    ⛔ АСУУДАЛ: `components/ListingDetailClient.jsx`-ийн `features` массив нь
 *       ЗӨВХӨН ҮЛ ХӨДЛӨХИЙН талбарууд байв (`rooms`/`area`/`floor`/`build_year`/
 *       `balconies`/`garage` …) → 🚗 машин, 💼 ажил, 💻 компьютер … зарууд дээр
 *       массив ХООСОН болж, **«Зарын дэлгэрэнгүй» карт ОГТ ГАРАХГҮЙ** байв ✗
 *       (бодит шалгалт: 🚗 Toyota Sai руу ороход зөвхөн «Тайлбар» харагдана).
 *    ✅ ОДОО: `attrs` нь ЗӨВХӨН хэсгийн (`attrFields`) шошго/icon/дарааллаар
 *       мөрүүд болж, дэлгэрэнгүй хуудсанд **2 БАГАНААР** харагдана ✓
 *
 * 📐 ЭХ СУРВАЛЖ = `getAttrFields(section, subtype)` — ⚠️ `CARD_ATTR_ORDER` БИШ:
 *    • `CARD_ATTR_ORDER` нь КАРТЫН товчилсон мөр (ж: 💻 Notebook-ийн 📺 `screen`
 *      тэнд БАЙХГҮЙ, `services`-ийн `experience` БАЙХГҮЙ ✗) тул дэлгэрэнгүй
 *      хүснэгтэд бүрэн бус болно
 *    • Дараалал нь ФОРМ/sidebar-ийн дараалал (хэрэглэгч форм дээр бичсэн
 *      дарааллаараа харна ✓)
 *    • `onlySubtypes` шүүлт АЖИЛЛАНА (ж: 📺/⚙️/🧠/💾 нь зөвхөн Notebook ба
 *      «Иж бүрэн компьютер»/«Процессор, сервер» дээр) ✓
 *    • Тодорхойлолтгүй түлхүүр `attrs`-д байсан ч ХАРАГДАХГҮЙ ✓ — ХАСАГДСАН
 *      `drive` (2026-10-01) ба `negotiable` (🤝 нь баруун баганад) автоматаар
 *      хасагдана ✓
 *
 * ⚠️ УТГЫН ФОРМАТ (картын мөрийн `formatAttrsLine`-ийн ИЖИЛ дүрэм):
 *    · `mileage` / `salary` → мянгатын таслалтай (`146,000`) — нэгж нь шошгонд
 *      байгаа тул («Гүйлт (км)», «Цалин (₮)») ДАВХАР залгахгүй ✓
 *    · `engine` → ЗӨВХӨН хуучин тоон утгад « л» (`2.5` → `2.5 л`); «2.1л - 2.7л»
 *      ба «Цахилгаан (EV)» нь нэгжээ өөрөө агуулна ✓
 *    · бусдыг (`year`, `color`, `transmission` …) ЗӨВӨӨР нь — шошго тайлбарлана ✓
 *
 * @param {string} section   хэсэг (`auto` …)
 * @param {object} attrs     `listings.attrs` (jsonb)
 * @param {string} [subtype] зарын дэд төрөл (`listings.property_type`)
 * @returns {{key:string,label:string,icon:string,value:string}[]}
 */
export function getAttrRows(section, attrs, subtype = '') {
  if (!attrs || typeof attrs !== 'object') return [];
  // ⚠️ `getAttrFields` нь `attrFields` БАЙХГҮЙ хэсэгт (`real-estate`) `[]`
  //    буцаана → ҮЛ ХӨДЛӨХИЙН зар дээр энэ функц ЯМАР Ч мөр нэмэхгүй ✓
  const rows = getAttrFields(section, subtype).reduce((out, f) => {
    const v = attrs[f.key];
    if (v === undefined || v === null || String(v).trim() === '') return out;
    out.push({ key: f.key, label: f.label, icon: f.icon || '', value: formatAttrValue(f.key, v) });
    return out;
  }, []);
  // 💳 ТӨЛБӨРИЙН НӨХЦӨЛ (2026-10-03) — хэрэглэгчийн хүсэлт: «…хайх хэсэгт
  //    гардаг болгоё» ⇒ зарын ДЭЛГЭРЭНГҮЙ хуудсанд ч харагдах ёстой.
  // ⚠️ `attrs.payment_terms` нь `attrFields`-д БАЙХГҮЙ (тэр нь хэсгийн
  //    жагсаалтаас БИШ, `lib/paymentFilter.mjs`-ээс удирдагдана) тул
  //    тусдаа мөр болж ХАМГИЙН ДОР очно ✓
  // ⚠️ ⛔ ХЭЗЭЭ Ч мөр нэмэхгүй байх 3 тохиолдол: ① хэсэг нь дэмжихгүй
  //    (`hasPaymentTerms` — ж: «Ажил»), ② утга хоосон/хүчингүй
  //    (`parsePaymentList` — `[]`/`'abc'` → `[]`), ③ `attrs` объект биш
  //    (дээрх `return []`) ⇒ «Хувь лизингээр» гэсэн хоосон мөр гарахгүй ✓
  const payments = attrs[PAYMENT_ATTR_KEY];
  if (hasPaymentTerms(section)) {
    const list = parsePaymentList(payments);
    if (list.length) {
      rows.push({
        key: PAYMENT_ATTR_KEY,
        label: 'Төлбөрийн нөхцөл',
        icon: '💳',
        // ⚠️ Монгол шошгоор (код БИШ) — хэрэглэгч «lease» гэж унших ёсгүй ✓
        value: paymentsFilterLabel(list),
      });
    }
  }
  return rows;
}

/** ⬆️ Нэг attr-ийн утгыг хүснэгтэд бэлэн текст болгоно (`getAttrRows`-ийн туслах) */
function formatAttrValue(key, v) {
  const raw = String(v).trim();
  // 💰/🛣️ Мөнгө ба гүйлт нь урт тоо — таслалтай бол «146,000» гэж уншигдана ✓
  if (key === 'mileage' || key === 'salary') {
    const n = Number(raw.replace(/\D/g, ''));
    return Number.isFinite(n) && n > 0 ? n.toLocaleString('en-US') : raw;
  }
  // 🔧 Хуучин/demo заруудын «2.5» л нэгжгүй (сонголттой утгууд нь нэгжээ агуулна)
  if (key === 'engine' && /^\d+(?:[.,]\d+)?$/.test(raw)) return `${raw} л`;
  return raw;
}


